"""IVR call routing service.

Handles config upsert, Dograh workflow provisioning, call log writing,
and analytics queries for the IVR module.
"""
from __future__ import annotations

import hashlib
import uuid
from datetime import datetime, timezone, timedelta
from typing import Optional

import httpx
import structlog
from sqlalchemy import func
from sqlalchemy.orm import Session

from app.core.config import settings
from app.core.encryption import decrypt_credentials, encrypt_credentials
from app.models.ivr import IVRCallLog, IVRConfig, IVROption
from app.schemas.ivr import IVRAnalyticsOut, IVRConfigIn

log = structlog.get_logger()

# Dograh local API (self-hosted, port 8000)
_DOGRAH_API = "http://localhost:8000"


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _phone_token(phone: str) -> str:
    return hashlib.sha256(phone.encode()).hexdigest()[:16]


# ── Config CRUD ───────────────────────────────────────────────────────────────

def get_config(db: Session, tenant_id: str) -> Optional[IVRConfig]:
    return (
        db.query(IVRConfig)
        .filter(IVRConfig.tenant_id == tenant_id)
        .first()
    )


def upsert_config(db: Session, tenant_id: str, data: IVRConfigIn) -> IVRConfig:
    """
    Create or replace IVR config for a tenant.
    Encrypts SIP credentials, replaces all options, then pushes workflow to Dograh.
    """
    sip_blob = encrypt_credentials({
        "username": data.vobiz_username,
        "password": data.vobiz_password,
        "server":   data.vobiz_server,
        "sip_number": data.sip_number,
    })

    config = get_config(db, tenant_id)
    if config is None:
        config = IVRConfig(id=str(uuid.uuid4()), tenant_id=tenant_id)
        db.add(config)

    config.greeting_text          = data.greeting_text
    config.language               = data.language
    config.sip_credentials_enc    = sip_blob
    config.business_hours_enabled = data.business_hours_enabled
    config.business_hours         = data.business_hours
    config.is_active              = True

    # Replace options: delete existing, insert new
    db.query(IVROption).filter(IVROption.ivr_config_id == config.id).delete()
    for opt in data.options:
        db.add(IVROption(
            id=str(uuid.uuid4()),
            tenant_id=tenant_id,
            ivr_config_id=config.id,
            digit=opt.digit,
            label=opt.label,
            spoken_text=opt.spoken_text,
            route_number=opt.route_number,
            department=opt.department,
        ))

    db.flush()

    # Push to Dograh (best-effort — don't fail the save if Dograh is unreachable)
    try:
        workflow_id = _push_to_dograh(config, data)
        config.dograh_workflow_id = workflow_id
        log.info("ivr_dograh_workflow_pushed", tenant_id=tenant_id, workflow_id=workflow_id)
    except Exception as exc:
        log.warning("ivr_dograh_push_failed", tenant_id=tenant_id, error=str(exc))

    db.commit()
    db.refresh(config)
    return config


# ── Dograh workflow builder ───────────────────────────────────────────────────

def _build_workflow(config: IVRConfig, data: IVRConfigIn) -> dict:
    """
    Build a Dograh workflow definition for DTMF IVR routing.

    Flow:
      1. TTS greeting (Sarvam voice, configured language)
      2. Gather DTMF — 1 digit, 10 s timeout
      3. Branch per digit → transfer to route_number
      4. Fallback (no input / invalid) → repeat once → hang up
    """
    # Build spoken menu from options sorted by digit
    menu_lines = [f"Press {o.digit} for {o.label}." for o in sorted(config.options, key=lambda x: x.digit)]
    full_greeting = f"{config.greeting_text} {' '.join(menu_lines)}"
    repeat_greeting = f"Sorry, we didn't catch that. {full_greeting}"

    # Build branch conditions
    branches = []
    for opt in sorted(config.options, key=lambda x: x.digit):
        branches.append({
            "condition": {"variable": "dtmf_digit", "operator": "equals", "value": str(opt.digit)},
            "action": {
                "type": "transfer",
                "phone_number": opt.route_number,
                "department": opt.department or opt.label,
            },
            "set_variables": {
                "department": opt.department or opt.label,
                "dtmf_digit": str(opt.digit),
            },
        })

    return {
        "name": f"HAIP IVR — {config.tenant_id[:8]}",
        "description": "Auto-generated by HAIP IVR routing module",
        "language": config.language,
        "voice_provider": "sarvam",
        "nodes": [
            {
                "id": "greeting",
                "type": "tts_speak",
                "text": full_greeting,
                "language": config.language,
                "next": "gather",
            },
            {
                "id": "gather",
                "type": "dtmf_gather",
                "timeout_seconds": 10,
                "num_digits": 1,
                "variable_name": "dtmf_digit",
                "branches": branches,
                "fallback": "retry",
            },
            {
                "id": "retry",
                "type": "tts_speak",
                "text": repeat_greeting,
                "language": config.language,
                "next": "gather2",
            },
            {
                "id": "gather2",
                "type": "dtmf_gather",
                "timeout_seconds": 10,
                "num_digits": 1,
                "variable_name": "dtmf_digit",
                "branches": branches,
                "fallback": "hangup",
            },
            {
                "id": "hangup",
                "type": "tts_speak",
                "text": "Thank you for calling. Goodbye.",
                "language": config.language,
                "next": "__end__",
            },
        ],
    }


def _push_to_dograh(config: IVRConfig, data: IVRConfigIn) -> str:
    """
    Push or update IVR workflow to Dograh local API.
    Returns the workflow_id.
    """
    workflow_payload = _build_workflow(config, data)
    dograh_url = settings.DOGRAH_SERVER_URL or _DOGRAH_API

    with httpx.Client(timeout=15.0) as client:
        if config.dograh_workflow_id:
            # Update existing workflow
            resp = client.put(
                f"{dograh_url}/api/v1/workflows/{config.dograh_workflow_id}",
                json=workflow_payload,
            )
        else:
            # Create new workflow
            resp = client.post(
                f"{dograh_url}/api/v1/workflows",
                json=workflow_payload,
            )
        resp.raise_for_status()
        result = resp.json()

    return result.get("id") or result.get("workflow_id") or config.dograh_workflow_id or ""


# ── Call log ──────────────────────────────────────────────────────────────────

def log_call_route(
    db: Session,
    tenant_id: str,
    dograh_call_id: Optional[str],
    digit: Optional[int],
    department: Optional[str],
    duration: int,
    caller_phone: Optional[str],
    call_id: Optional[str] = None,
) -> IVRCallLog:
    entry = IVRCallLog(
        id=str(uuid.uuid4()),
        tenant_id=tenant_id,
        call_id=call_id,
        dograh_call_id=dograh_call_id,
        digit_pressed=int(digit) if digit is not None else None,
        routed_to_department=department,
        duration_seconds=duration or 0,
        caller_phone_token=_phone_token(caller_phone) if caller_phone else None,
        called_at=_now(),
    )
    db.add(entry)
    db.flush()
    return entry


# ── Analytics ─────────────────────────────────────────────────────────────────

def get_analytics(db: Session, tenant_id: str, days: int = 30) -> IVRAnalyticsOut:
    since = _now() - timedelta(days=days)
    today_start = _now().replace(hour=0, minute=0, second=0, microsecond=0)

    rows = (
        db.query(IVRCallLog)
        .filter(
            IVRCallLog.tenant_id == tenant_id,
            IVRCallLog.called_at >= since,
        )
        .all()
    )

    total = len(rows)
    calls_today = sum(1 for r in rows if r.called_at >= today_start)
    avg_dur = sum(r.duration_seconds for r in rows) / total if total else 0.0

    calls_by_option: dict[str, int] = {}
    for r in rows:
        if r.digit_pressed is not None:
            key = str(r.digit_pressed)
            calls_by_option[key] = calls_by_option.get(key, 0) + 1

    top_option = max(calls_by_option, key=calls_by_option.get) if calls_by_option else None

    return IVRAnalyticsOut(
        total_calls=total,
        calls_by_option=calls_by_option,
        avg_duration_seconds=round(avg_dur, 1),
        calls_today=calls_today,
        top_option=top_option,
        days=days,
    )
