"""
Property Sharing Intelligence Service — M6

Creates trackable property share links and records downstream events
(view, revisit, forward, shortlist, inquiry_created).

Public API:
  record_share(db, tenant_id, property_id, shared_by_gid, channel, campaign_id)
      → PropertyShare (with tracking_token)

  record_event(db, tenant_id, tracking_token, event_type, viewer_gid, **kwargs)
      → PropertyShareEvent

  resolve_token(db, tenant_id, tracking_token)
      → PropertyShare | None
"""

from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import Optional

from sqlalchemy.orm import Session

from app.models.property_share import PropertyShare, PropertyShareEvent, ShareEventType
from app.models.base import gen_uuid

log = logging.getLogger(__name__)
_now = lambda: datetime.now(timezone.utc)


def record_share(
    db: Session,
    tenant_id: str,
    property_id: str,
    shared_by_gid: Optional[str] = None,
    channel: Optional[str] = None,
    campaign_id: Optional[str] = None,
) -> PropertyShare:
    """
    Create a new PropertyShare record and return its tracking_token.
    Call this when a property link is sent via WhatsApp / Instagram / SMS.
    """
    share = PropertyShare(
        id=gen_uuid(),
        tenant_id=tenant_id,
        property_id=property_id,
        shared_by_gid=shared_by_gid,
        channel=channel,
        campaign_id=campaign_id,
        # tracking_token is auto-generated by default=gen_tracking_token
    )
    db.add(share)
    db.flush()   # populate share.id and share.tracking_token

    # Also record the initial "shared" event
    _append_event(
        db, tenant_id=tenant_id, share_id=share.id,
        event_type=ShareEventType.SHARED,
        viewer_gid=shared_by_gid,
    )
    db.commit()
    log.info("property_shared", tenant_id=tenant_id, property_id=property_id,
             token=share.tracking_token, channel=channel)
    return share


def record_event(
    db: Session,
    tenant_id: str,
    tracking_token: str,
    event_type: str,
    viewer_gid: Optional[str] = None,
    referrer_gid: Optional[str] = None,
    session_id: Optional[str] = None,
    inquiry_id: Optional[str] = None,
) -> Optional[PropertyShareEvent]:
    """
    Record a downstream event for an existing share token.
    Updates the aggregate counters on the PropertyShare row.

    event_type values: viewed | revisited | forwarded | shortlisted | inquiry_created
    Returns None if token not found (graceful — tracking failures must not break flows).
    """
    share = resolve_token(db, tenant_id, tracking_token)
    if not share:
        log.warning("property_share_event_unknown_token",
                    tenant_id=tenant_id, token=tracking_token, event_type=event_type)
        return None

    evt = _append_event(
        db, tenant_id=tenant_id, share_id=share.id,
        event_type=event_type,
        viewer_gid=viewer_gid,
        referrer_gid=referrer_gid,
        session_id=session_id,
        inquiry_id=inquiry_id,
    )

    # Update aggregate counters
    if event_type == ShareEventType.VIEWED:
        share.total_views = (share.total_views or 0) + 1
    elif event_type == ShareEventType.REVISITED:
        share.total_revisits = (share.total_revisits or 0) + 1
    elif event_type == ShareEventType.FORWARDED:
        share.total_forwards = (share.total_forwards or 0) + 1
    elif event_type == ShareEventType.INQUIRY_CREATED:
        share.total_inquiries = (share.total_inquiries or 0) + 1
    db.add(share)
    db.commit()

    log.info("property_share_event", tenant_id=tenant_id, token=tracking_token,
             event_type=event_type, viewer_gid=viewer_gid)
    return evt


def resolve_token(
    db: Session,
    tenant_id: str,
    tracking_token: str,
) -> Optional[PropertyShare]:
    """Look up a PropertyShare by its tracking token."""
    return (
        db.query(PropertyShare)
        .filter_by(tenant_id=tenant_id, tracking_token=tracking_token)
        .first()
    )


# ─── Internal ─────────────────────────────────────────────────────────────────

def _append_event(
    db: Session,
    *,
    tenant_id: str,
    share_id: str,
    event_type: str,
    viewer_gid: Optional[str] = None,
    referrer_gid: Optional[str] = None,
    session_id: Optional[str] = None,
    inquiry_id: Optional[str] = None,
) -> PropertyShareEvent:
    evt = PropertyShareEvent(
        id=gen_uuid(),
        tenant_id=tenant_id,
        share_id=share_id,
        event_type=event_type,
        viewer_gid=viewer_gid,
        referrer_gid=referrer_gid,
        session_id=session_id,
        inquiry_id=inquiry_id,
        occurred_at=_now(),
    )
    db.add(evt)
    return evt
