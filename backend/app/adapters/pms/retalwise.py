"""
RentalWise Channel Manager / PMS adapter.

Authentication: HTTP Basic Auth (username + password) on every request.
Credentials are generated by your RentalWise Engagement Manager on onboarding.
Two environments: staging and production — base_url is provided per account.

API reference: https://apidocs.rentalwise.com/docs/rentalwise/

Endpoint groups:
  Content:       GET /properties, /property/{id}, /property-types, /amenities, /bed-types
  Availability:  GET /availability?propertyId=&from=&to=
  Rates:         GET /rates?propertyId=&from=&to=   (LOS rates)
  Reservations:  GET /reservations, GET /reservations/{id}
                 POST /quotes   (price quote before booking)
                 POST /reservations (create booking)
  Webhooks:      POST <your_url>  (push events: reservation.created, reservation.updated, etc.)
"""

from __future__ import annotations
import logging
from typing import Any
import httpx

logger = logging.getLogger(__name__)

# Default production base — https://app.rentalwise.io (REST API prefix: /rest/)
DEFAULT_BASE = "https://app.rentalwise.io"
# RentalWise's own domains. Any other base URL is tenant-supplied and must
# pass the SSRF check before the server calls it.
_TRUSTED_HOST_SUFFIXES = (".rentalwise.io", ".rentalwise.com")


def _check_base_url(base_url: str) -> None:
    from urllib.parse import urlsplit
    from app.core.url_safety import assert_public_url
    host = (urlsplit(base_url).hostname or "").lower()
    if urlsplit(base_url).scheme == "https" and any(("." + host).endswith(s) for s in _TRUSTED_HOST_SUFFIXES):
        return
    assert_public_url(base_url, allow_http=False)


class RentalwiseAdapter:
    def __init__(self, username: str = "", password: str = "", base_url: str = DEFAULT_BASE, api_token: str = ""):
        """
        Supports two auth modes:
          - Bearer token: pass api_token="12774|rw_production_..."
          - Basic auth:   pass username + password
        """
        self._base = base_url.rstrip("/")
        _check_base_url(self._base)
        if api_token:
            self._headers = {"Authorization": f"Bearer {api_token}", "Accept": "application/json"}
            self._auth = None
        else:
            self._headers = {"Accept": "application/json"}
            self._auth = (username, password) if username else None

    # ── Internal helpers ──────────────────────────────────────────────────────

    def _get(self, path: str, params: dict | None = None) -> Any:
        url = f"{self._base}/{path.lstrip('/')}"
        try:
            resp = httpx.get(url, auth=self._auth, headers=self._headers, params=params or {}, timeout=30)
            resp.raise_for_status()
            return resp.json()
        except httpx.HTTPStatusError as exc:
            logger.error(
                "RentalWise GET %s → %s %s",
                path, exc.response.status_code, exc.response.text[:300],
            )
            raise
        except Exception as exc:
            logger.error("RentalWise GET %s failed: %s", path, exc)
            raise

    def _post(self, path: str, payload: dict) -> Any:
        url = f"{self._base}/{path.lstrip('/')}"
        resp = httpx.post(url, auth=self._auth, headers=self._headers, json=payload, timeout=30)
        try:
            resp.raise_for_status()
        except httpx.HTTPStatusError as exc:
            logger.error(
                "RentalWise POST %s → %s %s",
                path, exc.response.status_code, exc.response.text[:300],
            )
            raise
        return resp.json()

    # ── Content endpoints ─────────────────────────────────────────────────────

    def get_properties(self) -> list[dict]:
        """POST /rest/property/query — list all properties."""
        payload = {"paginate": {"page": 1, "perpage": 200}, "sort": [], "where": {}, "with": []}
        data = self._post("/rest/property/query", payload)
        items = data if isinstance(data, list) else data.get("data", data.get("properties", data.get("items", [])))
        return [self._normalise_property(p) for p in items]

    def get_property(self, property_id: str) -> dict:
        """POST /rest/property/query filtered by id."""
        payload = {"paginate": {"page": 1, "perpage": 1}, "where": {"conditions": [{"field": "id", "value": property_id, "__condition__": "="}]}}
        data = self._post("/rest/property/query", payload)
        items = data if isinstance(data, list) else data.get("data", data.get("properties", []))
        return self._normalise_property(items[0]) if items else {}

    @staticmethod
    def _str(val: any, fallback: str = "") -> str:
        """Extract string from either a plain string or a multilingual dict like {'en': 'name'}."""
        if val is None:
            return fallback
        if isinstance(val, dict):
            return str(val.get("en") or val.get("EN") or next(iter(val.values()), fallback) or fallback)
        return str(val) if val else fallback

    def _normalise_property(self, p: dict) -> dict:
        # location.name contains the city (Translated dict)
        location = p.get("location") or {}
        city = self._str(location.get("name", p.get("city", "")))

        # property_type is a nested object {id, name} or a plain string
        ptype_raw = p.get("property_type", p.get("type", p.get("propertyType", "villa")))
        if isinstance(ptype_raw, dict):
            ptype = self._str(ptype_raw.get("name", "villa"))
        else:
            ptype = self._str(ptype_raw) or "villa"

        # images: each image has thumbnail/medium/large/original URLs
        images_raw = p.get("images", [])
        images = [
            img.get("large") or img.get("medium") or img.get("original") or img.get("thumbnail")
            for img in images_raw
            if isinstance(img, dict)
        ]

        # amenities: list of {id, name (Translated), original_name, ...}
        amenities_raw = p.get("amenities", [])
        amenities = [
            self._str(a.get("name", a.get("original_name", "")))
            for a in amenities_raw
            if isinstance(a, dict)
        ]

        return {
            "external_id": str(p.get("id", p.get("propertyId", p.get("property_id", "")))),
            "name": self._str(p.get("name", p.get("propertyName", ""))),
            "type": ptype,
            "city": city,
            "address": self._str(p.get("address", "")),
            "max_guests": int(p.get("max_occupancy", p.get("maxGuests", p.get("max_guests", p.get("max_adults", 0)))) or 0),
            "bedrooms": int(p.get("bedrooms", p.get("bedroomsCount", 0)) or 0),
            "bathrooms": int(p.get("bathrooms", p.get("bathroomsCount", 0)) or 0),
            "description": self._str(p.get("description", "")),
            "amenities": amenities,
            "images": [img for img in images if img],
            "raw": p,
        }

    # ── Availability ──────────────────────────────────────────────────────────

    def get_availability(self, property_id: str, date_from: str, date_to: str) -> list[dict]:
        """
        POST /property/get-rates-availability
        Returns per-night availability + rates for a property.
        date_from / date_to: YYYY-MM-DD
        """
        return self._post("/rest/property/get-rates-availability", {
            "property": int(property_id),
            "daterange": {"start": date_from, "end": date_to},
            "fill_default_values": True,
        })

    # ── Rates ────────────────────────────────────────────────────────────────

    def get_rates(self, property_id: str, date_from: str, date_to: str) -> list[dict]:
        """
        POST /property/rates-with-ranges — rates grouped by date range.
        """
        return self._post("/rest/property/rates-with-ranges", {
            "property": int(property_id),
            "daterange": {"start": date_from, "end": date_to},
            "fill_default_values": True,
        })

    def fetch_property(self, property_id: str) -> dict:
        """
        POST /property/fetch — full property details including images and amenities.
        """
        try:
            data = self._post("/rest/property/fetch", {"id": int(property_id), "with": ["images", "amenities", "location", "property_type"]})
            return self._normalise_property(data) if data else {}
        except Exception as exc:
            logger.warning("RentalWise fetch_property %s failed: %s", property_id, exc)
            return {}

    # ── Reservations ──────────────────────────────────────────────────────────

    def get_reservations(self, limit: int = 200, offset: int = 0) -> list[dict]:
        """POST /booking/query — list bookings."""
        page = (offset // limit) + 1
        payload = {
            "paginate": {"page": page, "perpage": limit},
            "sort": [{"field": "id", "direction": "desc"}],
            "where": {},
            "with": ["main_guest", "property", "currency"],
        }
        try:
            data = self._post("/rest/booking/query", payload)
        except Exception:
            return []
        items = data if isinstance(data, list) else data.get("data", data.get("bookings", data.get("items", [])))
        return [self._normalise_reservation(r) for r in items]

    def get_reservation(self, reservation_id: str) -> dict:
        """POST /rest/booking/query filtered by id."""
        payload = {
            "paginate": {"page": 1, "perpage": 1},
            "where": {"conditions": [{"field": "id", "value": reservation_id, "__condition__": "="}]},
            "with": ["main_guest", "property", "currency"],
        }
        try:
            data = self._post("/rest/booking/query", payload)
        except Exception:
            return {}
        items = data if isinstance(data, list) else data.get("data", [])
        return self._normalise_reservation(items[0]) if items else {}

    def create_reservation(self, payload: dict) -> dict:
        """POST /rest/booking — create a booking."""
        return self._post("/rest/booking", payload)

    def _normalise_reservation(self, r: dict) -> dict:
        # main_guest is the GuestAccount object
        guest = r.get("main_guest") or r.get("guest") or r.get("guestDetails") or {}
        guest_name = " ".join(filter(None, [
            self._str(guest.get("first_name", guest.get("firstName", ""))),
            self._str(guest.get("last_name", guest.get("lastName", ""))),
        ])) or self._str(guest.get("name", guest.get("fullName", ""))) or self._str(r.get("guestName", ""))

        # currency: Currency object with iso_code
        currency_raw = r.get("currency", "INR")
        currency = currency_raw.get("iso_code", "INR") if isinstance(currency_raw, dict) else str(currency_raw or "INR")

        # channel: source_name is a plain string; channel may be a nested object
        channel_raw = r.get("source_name") or r.get("channel_source") or r.get("channel") or "direct"
        channel = channel_raw.get("name", "direct") if isinstance(channel_raw, dict) else str(channel_raw or "direct")

        # property: Property object with id
        prop_raw = r.get("property") or r.get("propertyId") or r.get("property_id") or ""
        property_id = str(prop_raw.get("id", "") if isinstance(prop_raw, dict) else prop_raw or "")

        # dates: API uses checkin/checkout (no underscore)
        check_in = self._str(r.get("checkin", r.get("check_in", r.get("checkIn", r.get("arrival", "")))))
        check_out = self._str(r.get("checkout", r.get("check_out", r.get("checkOut", r.get("departure", "")))))

        # total price
        total = float(r.get("total", r.get("totalAmount", r.get("total_amount", r.get("price", 0)))) or 0)

        return {
            "external_id": str(r.get("id", r.get("reservationId", r.get("reservation_id", "")))),
            "property_id": property_id,
            "guest_name": guest_name,
            "guest_phone": self._str(
                guest.get("phone", guest.get("mobile", guest.get("phone_number", "")))
                or r.get("guestPhone", r.get("guest_phone", ""))
            ),
            "guest_email": self._str(
                guest.get("email", "")
                or r.get("guestEmail", r.get("guest_email", ""))
            ),
            "check_in": check_in,
            "check_out": check_out,
            "status": self._str(r.get("status", "confirmed")),
            "channel": channel,
            "total_amount": total,
            "currency": currency,
            "nights": int(r.get("nights", 0) or 0),
            "guests_count": int(r.get("adults", r.get("guests", r.get("guestsCount", 0))) or 0),
            "raw": r,
        }

    def get_guests(self, limit: int = 500) -> list[dict]:
        """Extract unique guests from bookings (RentalWise has no standalone /guests endpoint)."""
        try:
            reservations = self.get_reservations(limit=limit)
            seen: set[str] = set()
            guests = []
            for r in reservations:
                phone = r.get("guest_phone", "").strip()
                email = r.get("guest_email", "").strip()
                # Use phone as primary key; fall back to email if no phone
                key = phone or email
                if key and key not in seen:
                    seen.add(key)
                    guests.append({
                        "phone": phone,
                        "name": r.get("guest_name", ""),
                        "email": email,
                    })
            return guests
        except Exception:
            return []

    # ── Availability statuses ─────────────────────────────────────────────────

    def get_availability_statuses(
        self,
        property_id: str | int | None = None,
        date_from: str | None = None,
        date_to: str | None = None,
        page: int = 1,
        per_page: int = 500,
    ) -> list[dict]:
        """
        POST /rest/availability-status/query
        Returns per-day availability status records (available / booked / blocked /
        maintenance / owner_use / hold / etc.) for one or all properties.

        Each record shape (normalised):
            {
                "id":          str,
                "property_id": str,
                "date":        "YYYY-MM-DD",
                "status":      "available" | "booked" | "blocked" | "maintenance" | "owner_use" | ...,
                "note":        str | None,
                "raw":         dict,
            }
        """
        payload: dict = {
            "paginate": {"page": page, "perpage": per_page},
            "sort": [{"field": "date", "direction": "asc"}],
            "where": {},
        }
        conditions: list[dict] = []
        if property_id is not None:
            conditions.append({
                "field": "property_id",
                "value": int(property_id),
                "__condition__": "=",
            })
        if date_from:
            conditions.append({"field": "date", "value": date_from, "__condition__": ">="})
        if date_to:
            conditions.append({"field": "date", "value": date_to, "__condition__": "<="})
        if conditions:
            payload["where"] = {"conditions": conditions}

        try:
            data = self._post("/rest/availability-status/query", payload)
        except Exception as exc:
            logger.warning("RentalWise availability-status/query failed: %s", exc)
            return []

        items = (
            data if isinstance(data, list)
            else data.get("data", data.get("items", data.get("availability_statuses", [])))
        )
        return [self._normalise_availability_status(item) for item in items]

    def get_all_availability_statuses_paginated(
        self,
        property_id: str | int | None = None,
        date_from: str | None = None,
        date_to: str | None = None,
        per_page: int = 500,
    ) -> list[dict]:
        """Fetch all pages of availability-status records."""
        results: list[dict] = []
        page = 1
        while True:
            batch = self.get_availability_statuses(
                property_id=property_id,
                date_from=date_from,
                date_to=date_to,
                page=page,
                per_page=per_page,
            )
            results.extend(batch)
            if len(batch) < per_page:
                break
            page += 1
        return results

    @staticmethod
    def _normalise_availability_status(item: dict) -> dict:
        """Normalise a raw availability-status record to a flat dict."""
        raw_status = item.get("status", "available")
        # status may be an object: {id, name, slug} or a plain string/slug
        if isinstance(raw_status, dict):
            status = str(
                raw_status.get("slug")
                or raw_status.get("name")
                or raw_status.get("id")
                or "available"
            ).lower()
        else:
            status = str(raw_status or "available").lower()

        prop_raw = item.get("property_id") or item.get("property", {})
        if isinstance(prop_raw, dict):
            property_id = str(prop_raw.get("id", ""))
        else:
            property_id = str(prop_raw or "")

        return {
            "id":          str(item.get("id", "")),
            "property_id": property_id,
            "date":        str(item.get("date", "")),
            "status":      status,
            "note":        item.get("note") or item.get("notes") or item.get("description"),
            "raw":         item,
        }

    # ── iCal feeds ───────────────────────────────────────────────────────────

    def fetch_property_ical(self, property_id: str | int) -> str:
        """
        GET /rest/property-ical/fetch?property_id={id}
        Returns the raw iCal text for a property.
        Raises on error.
        """
        url = f"{self._base}/rest/property-ical/fetch"
        try:
            import httpx as _httpx
            resp = _httpx.get(
                url,
                auth=self._auth,
                headers={**self._headers, "Accept": "text/calendar, text/plain, */*"},
                params={"property_id": int(property_id)},
                timeout=30,
                follow_redirects=True,
            )
            resp.raise_for_status()
            return resp.text
        except Exception as exc:
            logger.error("RentalWise property-ical/fetch %s failed: %s", property_id, exc)
            raise

    def parse_ical_blocks(self, ical_text: str, property_id: str) -> list[dict]:
        """
        Parse a VCALENDAR / VEVENT text into normalised block/stay records.
        Returns list of dicts with keys: external_id, property_id, dtstart, dtend,
        summary, status, uid.

        Uses built-in Python only — no icalendar library required.
        """
        events: list[dict] = []
        current: dict | None = None
        for raw_line in ical_text.splitlines():
            line = raw_line.strip()
            if line == "BEGIN:VEVENT":
                current = {}
            elif line == "END:VEVENT" and current is not None:
                uid     = current.get("UID", "")
                summary = current.get("SUMMARY", "")
                dtstart = current.get("DTSTART", "")
                dtend   = current.get("DTEND", "")
                if dtstart and dtend:
                    events.append({
                        "external_id": uid or f"ical-{property_id}-{dtstart}",
                        "property_id": property_id,
                        "dtstart":     dtstart[:10],  # keep YYYY-MM-DD portion
                        "dtend":       dtend[:10],
                        "summary":     summary,
                        "status":      "blocked",
                        "uid":         uid,
                    })
                current = None
            elif current is not None and ":" in line:
                # Handle param-folded lines: DTSTART;VALUE=DATE:20250601
                key, _, value = line.partition(":")
                key = key.split(";")[0]  # strip params
                current[key] = value
        return events

    # ── Health check ──────────────────────────────────────────────────────────

    def ping(self) -> bool:
        """Verify credentials are valid. Returns True on success."""
        try:
            self._post("/rest/property/query", {"paginate": {"page": 1, "perpage": 1}})
            return True
        except Exception:
            return False
