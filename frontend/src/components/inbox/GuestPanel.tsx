"use client";
import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { useSession } from "next-auth/react";
import { Star, Sparkles, Calendar, Users, Wallet, Phone, Mail, Loader2, MapPin, Heart, MessageSquare, FileText } from "@/lib/icons";
import { Bed, UserCheck } from "lucide-react";
import { ChannelIcon, channelLabel } from "./ChannelIcon";
import { Skeleton } from "@/components/ui/skeleton";
import { ProfileCompletenessWidget } from "./ProfileCompletenessWidget";
import { FollowUpTasksPanel } from "./FollowUpTasksPanel";
import { useToast } from "@/components/ui/toast";
import api from "@/lib/api";

interface ConversationDetail {
  id: string;
  guest_id?: string;
  inquiry_id?: string | null;
  guest_name?: string;
  guest_phone: string;
  channel: string;
  status: "open" | "resolved" | "snoozed";
}

// HAIP Inbox UI-fidelity/full-parity passes: same GET /leads/{inquiry_id}
// query ProfileCompletenessWidget/PinnedInquiryBanner already fetch
// (identical queryKey below, so react-query dedupes this into the same
// network call) -- carries assigned_agent_name/stage_key, the AI summary
// already generated by generate_ai_summary.py, and inquiry specs, none of
// which conversations.py's own detail endpoint serializes.
interface LeadOwnerStage {
  inquiry_id: string;
  assigned_agent_name?: string | null;
  assigned_agent_id?: string | null;
  stage_key?: string | null;
  ai_summary?: string | null;
  ai_analysis?: {
    intent?: string;
    sentiment?: string;
    objection?: string | null;
    reply_urgency?: string;
    next_action?: string;
  } | null;
  check_in?: string | null;
  check_out?: string | null;
  adults?: number | null;
  children?: number | null;
  budget_estimate?: number | null;
  budget_currency?: string;
  budget_range_label?: string | null;
  occasion?: string | null;
  property_interest?: string[];
  // special_requests arrives via the tenant-configurable Lead Field
  // Registry (migration 044), not a dedicated schema field -- same source
  // leads/[inquiryId]/page.tsx's Trip Details card reads.
  custom_field_values?: { field_key: string; label: string; data_type: string; value: unknown }[];
  // Auto-send soft-escalation plan: the AI's last reply already went out,
  // but it judged the outcome needs a human's personal follow-up.
  needs_agent_followup?: boolean;
  needs_agent_followup_reason?: string | null;
}

interface PipelineStage {
  id: string;
  key: string;
  label: string;
}

interface GuestSummary {
  id?: string;
  name?: string;
  phone: string;
  email?: string | null;
  tags?: string[];
  consent_status?: string;
  is_vip?: boolean;
  lifetime_value?: number;
  total_stays?: number;
  total_inquiries?: number;
  recent_stays?: { property_name?: string; check_in?: string; check_out?: string }[];
}

interface TeamMember {
  id: string;
  name: string;
}

export function GuestPanel({ detail, mobileVariant }: { detail: ConversationDetail; mobileVariant?: boolean }) {
  const { toast } = useToast();
  const qc = useQueryClient();
  const { data: session } = useSession();
  const inquiryId = detail.inquiry_id ?? null;
  const currentUserId = session?.user?.id;
  const canAssignAnyone = session?.user?.role === "owner" || session?.user?.role === "manager";

  const { data: leadOwnerStage } = useQuery<LeadOwnerStage>({
    queryKey: ["lead-detail", inquiryId],
    queryFn: () => api.get(`/leads/${inquiryId}`).then(r => r.data),
    enabled: !!inquiryId,
    staleTime: 30_000,
  });

  const { data: stages } = useQuery<PipelineStage[]>({
    queryKey: ["pipeline-stages"],
    queryFn: () => api.get("/pipeline-stages").then(r => r.data),
    staleTime: 60_000,
  });

  const moveStage = useMutation({
    mutationFn: (newStageId: string) =>
      api.post("/automations/actions/execute", {
        action_type: "move_stage",
        entity_refs: { inquiry_id: inquiryId },
        action_config: { new_stage_id: newStageId },
        source: "inbox_guest_panel",
      }),
    onSuccess: () => {
      toast({ title: "Lead stage updated" });
      qc.invalidateQueries({ queryKey: ["lead-detail", inquiryId] });
      qc.invalidateQueries({ queryKey: ["conversations"] });
    },
    onError: (e: unknown) => {
      const msg = (e as { response?: { data?: { detail?: string } } })?.response?.data?.detail;
      toast({ variant: "error", title: "Could not update stage", description: typeof msg === "string" ? msg : "Please try again." });
    },
  });

  // GET /users is owner/manager-only server-side (settings/team/page.tsx's
  // same query) -- only fetched here for roles that can actually call it, so
  // a reservations-role agent isn't sent a 403 just for opening this panel.
  const { data: teamMembers } = useQuery<TeamMember[]>({
    queryKey: ["team-members"],
    queryFn: () => api.get("/users").then(r => r.data),
    enabled: canAssignAnyone,
    staleTime: 60_000,
  });

  // Real gap, reported live: assign_to already exists as a full backend
  // action (automation_engine.py's _action_assign_to, reused by
  // app/mcp/tools.py's _assign_lead) but no UI anywhere ever called it --
  // "Assigned Owner" was read-only. Same one-click action endpoint
  // moveStage above already uses. Any authenticated user may call this
  // (matches execute_recommended_action's own docstring), so a
  // reservations-role agent can self-assign even without the full
  // team-member dropdown (which needs owner/manager to populate).
  const assignLead = useMutation({
    mutationFn: (userId: string) =>
      api.post("/automations/actions/execute", {
        action_type: "assign_to",
        entity_refs: { inquiry_id: inquiryId },
        action_config: { user_id: userId },
        source: "inbox_guest_panel",
      }),
    onSuccess: () => {
      toast({ title: "Lead assigned" });
      qc.invalidateQueries({ queryKey: ["lead-detail", inquiryId] });
      qc.invalidateQueries({ queryKey: ["conversations"] });
    },
    onError: (e: unknown) => {
      const msg = (e as { response?: { data?: { detail?: string } } })?.response?.data?.detail;
      toast({ variant: "error", title: "Could not assign lead", description: typeof msg === "string" ? msg : "Please try again." });
    },
  });

  // Mcube-disconnect + outbound-calling pass: same POST /calls/click-to-call
  // ConversationList's hover Quick Call button uses -- Vobiz (or whichever
  // IVR is active) rings the agent's registered mobile first, then bridges
  // to the guest. No audio in the browser.
  const clickToCall = useMutation({
    mutationFn: (guest_number: string) => api.post("/calls/click-to-call", { guest_number }),
    onSuccess: () => toast({ variant: "success", title: "Calling…", description: "Your phone will ring shortly." }),
    onError: (e: unknown) => {
      const msg = (e as { response?: { data?: { detail?: string } } })?.response?.data?.detail;
      toast({ variant: "error", title: "Could not start call", description: typeof msg === "string" ? msg : "Please try again." });
    },
  });

  const { data: guest, isLoading } = useQuery<GuestSummary>({
    queryKey: ["guest-by-phone", detail.guest_phone],
    queryFn: () =>
      api.get(`/guests?phone=${encodeURIComponent(detail.guest_phone)}&limit=1`)
         .then(r => Array.isArray(r.data) ? r.data[0] : r.data),
    enabled: !!detail.guest_phone,
    staleTime: 60_000,
  });

  const initial = (detail.guest_name ?? detail.guest_phone)?.[0]?.toUpperCase() ?? "?";
  const isVip = guest?.is_vip;

  return (
    <div
      className={
        mobileVariant
          ? "flex flex-col w-full h-full overflow-y-auto haip-scrollbar bg-card"
          : "hidden md:flex md:flex-col w-[300px] flex-shrink-0 overflow-y-auto haip-scrollbar bg-card"
      }
      style={mobileVariant ? undefined : { borderLeft: "1px solid var(--haip-border)" }}
    >
      {/* Header */}
      <div className="px-4 py-4 flex-shrink-0" style={{ borderBottom: "1px solid var(--haip-border)" }}>
        <p className="text-[10px] font-medium uppercase tracking-widest mb-3" style={{ color: "var(--haip-fg-subtle)" }}>
          Guest 360
        </p>
        <div className="flex items-center gap-3">
          <div
            className="w-9 h-9 rounded-full flex items-center justify-center font-bold text-sm flex-shrink-0"
            style={{
              background: isVip
                ? "linear-gradient(135deg, #F59E0B, #D97706)"
                : "var(--primary)",
              color: "var(--primary-foreground)",
            }}
          >
            {initial}
          </div>
          <div className="min-w-0">
            <div className="flex items-center gap-1.5">
              <p className="text-[13px] font-semibold truncate" style={{ color: "var(--haip-fg)" }}>
                {detail.guest_name || "Unknown"}
              </p>
              {isVip && <Star size={10} className="flex-shrink-0" style={{ color: "#F59E0B" }} fill="#F59E0B" />}
            </div>
            <p className="text-[10px] truncate" style={{ color: "var(--haip-fg-subtle)" }}>
              ···{detail.guest_phone.slice(-4)}
            </p>
          </div>
        </div>
      </div>

      {/* Body */}
      <div className="flex-1 px-4 py-4 space-y-4">
        {isLoading ? (
          <div className="space-y-2.5">
            <Skeleton className="h-3 w-3/4 rounded" />
            <Skeleton className="h-3 w-1/2 rounded" />
            <Skeleton className="h-3 w-2/3 rounded" />
          </div>
        ) : (
          <>
            {/* Trip Details -- same card as leads/[inquiryId]/page.tsx's
                Overview tab: guests, dates, property/route, budget,
                occasion, special requests. Reads the same /leads/{inquiry_id}
                response GuestPanel already fetches -- special_requests
                comes off the Lead Field Registry (migration 044) via
                custom_field_values, same as the Leads360 detail page.
                Placed first in the panel body (replacing the old LTV
                stats row, which was frequently all-zero noise for a
                fresh lead) since trip intent is the most actionable
                thing an agent needs at a glance. */}
            {(() => {
              const specialRequests = (leadOwnerStage?.custom_field_values ?? []).find(f => f.field_key === "special_requests");
              const guestCountLabel = leadOwnerStage
                ? [
                    leadOwnerStage.adults ? `${leadOwnerStage.adults} adult${leadOwnerStage.adults > 1 ? "s" : ""}` : null,
                    leadOwnerStage.children ? `${leadOwnerStage.children} child${leadOwnerStage.children > 1 ? "ren" : ""}` : null,
                  ].filter(Boolean).join(", ") || null
                : null;
              const datesLabel = leadOwnerStage?.check_in
                ? `${new Date(leadOwnerStage.check_in).toLocaleDateString("en-IN", { day: "numeric", month: "short" })}${leadOwnerStage.check_out ? ` → ${new Date(leadOwnerStage.check_out).toLocaleDateString("en-IN", { day: "numeric", month: "short" })}` : ""}`
                : null;
              const budgetLabel = leadOwnerStage?.budget_range_label
                ?? (leadOwnerStage?.budget_estimate != null ? `${leadOwnerStage.budget_currency ?? "INR"} ${leadOwnerStage.budget_estimate.toLocaleString("en-IN")}` : null);
              const routeLabel = (leadOwnerStage?.property_interest ?? [])[0] ?? null;
              const hasAny = guestCountLabel || datesLabel || routeLabel || budgetLabel || leadOwnerStage?.occasion || (specialRequests?.value != null && specialRequests.value !== "");
              if (!hasAny) return null;
              return (
                <div className="haip-card p-3.5 space-y-2" style={{ background: "var(--muted)" }}>
                  <p className="text-[10px] font-bold uppercase tracking-wider flex items-center gap-1.5" style={{ color: "var(--haip-fg-subtle)" }}>
                    <FileText size={11} />
                    Trip Details
                  </p>
                  <div className="grid grid-cols-2 gap-2 text-[11px]">
                    {guestCountLabel && (
                      <div className="p-2 rounded-lg" style={{ background: "var(--card)", border: "1px solid var(--haip-border)" }}>
                        <span className="flex items-center gap-1 text-[9px]" style={{ color: "var(--haip-fg-subtle)" }}><Users size={9} />Guests</span>
                        <span className="font-bold" style={{ color: "var(--haip-fg)" }}>{guestCountLabel}</span>
                      </div>
                    )}
                    {datesLabel && (
                      <div className="p-2 rounded-lg" style={{ background: "var(--card)", border: "1px solid var(--haip-border)" }}>
                        <span className="flex items-center gap-1 text-[9px]" style={{ color: "var(--haip-fg-subtle)" }}><Calendar size={9} />Dates</span>
                        <span className="font-bold tabular-nums" style={{ color: "var(--haip-fg)" }}>{datesLabel}</span>
                      </div>
                    )}
                    {routeLabel && (
                      <div className="p-2 rounded-lg" style={{ background: "var(--card)", border: "1px solid var(--haip-border)" }}>
                        <span className="flex items-center gap-1 text-[9px]" style={{ color: "var(--haip-fg-subtle)" }}><MapPin size={9} />Property / Route</span>
                        <span className="font-bold truncate block" style={{ color: "var(--haip-fg)" }}>{routeLabel}</span>
                      </div>
                    )}
                    {budgetLabel && (
                      <div className="p-2 rounded-lg" style={{ background: "var(--card)", border: "1px solid var(--haip-border)" }}>
                        <span className="flex items-center gap-1 text-[9px]" style={{ color: "var(--haip-fg-subtle)" }}><Wallet size={9} />Budget</span>
                        <span className="font-bold" style={{ color: "var(--haip-fg)" }}>{budgetLabel}</span>
                      </div>
                    )}
                    {leadOwnerStage?.occasion && (
                      <div className="p-2 rounded-lg" style={{ background: "var(--card)", border: "1px solid var(--haip-border)" }}>
                        <span className="flex items-center gap-1 text-[9px]" style={{ color: "var(--haip-fg-subtle)" }}><Heart size={9} />Occasion</span>
                        <span className="font-bold capitalize" style={{ color: "var(--haip-fg)" }}>{leadOwnerStage.occasion}</span>
                      </div>
                    )}
                    {specialRequests?.value != null && specialRequests.value !== "" && (
                      <div className="col-span-2 p-2 rounded-lg" style={{ background: "var(--card)", border: "1px solid var(--haip-border)" }}>
                        <span className="flex items-center gap-1 text-[9px]" style={{ color: "var(--haip-fg-subtle)" }}><MessageSquare size={9} />Special Requests</span>
                        <span className="font-medium" style={{ color: "var(--haip-fg)" }}>{String(specialRequests.value)}</span>
                      </div>
                    )}
                  </div>
                </div>
              );
            })()}

            {/* Tags */}
            {(guest?.tags ?? []).length > 0 && (
              <div className="flex flex-wrap gap-1">
                {guest!.tags!.slice(0, 4).map(tag => (
                  <span
                    key={tag}
                    className="px-2 py-0.5 rounded-full text-[10px] font-medium capitalize"
                    style={{
                      background: "color-mix(in srgb, var(--primary) 10%, transparent)",
                      color: "var(--primary)",
                    }}
                  >
                    {tag}
                  </span>
                ))}
              </div>
            )}

            {/* Channel + status */}
            <div className="flex items-center justify-between">
              <div className="flex items-center gap-1.5">
                <ChannelIcon channel={detail.channel} />
                <span className="text-[11px]" style={{ color: "var(--haip-fg-muted)" }}>
                  {channelLabel(detail.channel)}
                </span>
              </div>
              <span
                className="px-2 py-0.5 rounded-full text-[10px] font-medium capitalize"
                style={{
                  background: detail.status === "open"
                    ? "color-mix(in srgb, var(--primary) 10%, transparent)"
                    : "var(--muted)",
                  color: detail.status === "open" ? "var(--primary)" : "var(--haip-fg-subtle)",
                }}
              >
                {detail.status}
              </span>
            </div>

            {/* HAIP Inbox UI-fidelity pass, ticket 5: Guest Overview --
                Assigned Owner (read-only) + Lead Stage (dropdown, wired to
                the existing move_stage one-click action). Both were
                confirmed gaps: assigned_to lives on Conversation, stage on
                Inquiry, neither was shown anywhere in this panel before. */}
            {inquiryId && (
              <div
                className="haip-card p-3 space-y-2 text-[11px]"
                style={{ background: "var(--muted)" }}
              >
                <p className="text-[10px] font-bold uppercase tracking-wider" style={{ color: "var(--haip-fg-subtle)" }}>
                  Guest Overview
                </p>
                <div className="flex items-center justify-between">
                  <span style={{ color: "var(--haip-fg-subtle)" }}>Phone</span>
                  {(() => {
                    // guest?.phone comes from a separate /guests?phone= lookup that
                    // can miss (e.g. Guest.phone unbackfilled) even though the
                    // conversation itself already carries the number -- fall back
                    // to detail.guest_phone (proven present, it's what the masked
                    // header renders) instead of showing "Not on file" wrongly.
                    const phone = guest?.phone || detail.guest_phone;
                    return phone ? (
                      <button
                        type="button"
                        onClick={() => clickToCall.mutate(phone)}
                        disabled={clickToCall.isPending}
                        title="Call via IVR"
                        className="font-semibold flex items-center gap-1 hover:underline disabled:opacity-50"
                        style={{ color: "var(--haip-fg)" }}
                      >
                        {clickToCall.isPending
                          ? <Loader2 size={11} className="animate-spin" style={{ color: "var(--primary)" }} />
                          : <Phone size={11} style={{ color: "var(--primary)" }} />}
                        {phone}
                      </button>
                    ) : (
                      <span className="font-semibold flex items-center gap-1" style={{ color: "var(--haip-amber, #d97706)" }}>
                        <Phone size={11} style={{ color: "var(--haip-amber, #d97706)" }} />
                        Not on file
                      </span>
                    );
                  })()}
                </div>
                <div className="flex items-center justify-between">
                  <span style={{ color: "var(--haip-fg-subtle)" }}>Email</span>
                  <span className="font-semibold flex items-center gap-1 truncate" style={{ color: guest?.email ? "var(--haip-fg)" : "var(--haip-fg-subtle)" }}>
                    <Mail size={11} style={{ color: "var(--primary)" }} />
                    {guest?.email || "N/A"}
                  </span>
                </div>
                <div className="flex items-center justify-between gap-2">
                  <span style={{ color: "var(--haip-fg-subtle)" }}>Assigned Owner</span>
                  {canAssignAnyone ? (
                    <select
                      value={leadOwnerStage?.assigned_agent_id ?? ""}
                      onChange={e => e.target.value && assignLead.mutate(e.target.value)}
                      disabled={assignLead.isPending}
                      className="font-semibold text-[11px] rounded-md px-1.5 py-0.5 border outline-none disabled:opacity-60"
                      style={{ borderColor: "var(--haip-border)", background: "var(--card)", color: "var(--primary)" }}
                    >
                      <option value="" disabled>Unassigned</option>
                      {(teamMembers ?? []).map(m => (
                        <option key={m.id} value={m.id}>{m.id === currentUserId ? `${m.name} (you)` : m.name}</option>
                      ))}
                    </select>
                  ) : (
                    <span className="font-semibold flex items-center gap-1.5" style={{ color: "var(--haip-fg)" }}>
                      <UserCheck size={11} style={{ color: "var(--primary)" }} />
                      {leadOwnerStage?.assigned_agent_id === currentUserId
                        ? "You"
                        : leadOwnerStage?.assigned_agent_name || "Unassigned"}
                      {leadOwnerStage?.assigned_agent_id !== currentUserId && currentUserId && (
                        <button
                          onClick={() => assignLead.mutate(currentUserId)}
                          disabled={assignLead.isPending}
                          className="text-[10px] font-medium rounded-md px-1.5 py-0.5 border disabled:opacity-60"
                          style={{ borderColor: "var(--haip-border)", color: "var(--primary)" }}
                        >
                          Assign to me
                        </button>
                      )}
                    </span>
                  )}
                </div>
                <div className="flex items-center justify-between gap-2">
                  <span style={{ color: "var(--haip-fg-subtle)" }}>Lead Stage</span>
                  <select
                    value={stages?.find(s => s.key === leadOwnerStage?.stage_key)?.id ?? ""}
                    onChange={e => e.target.value && moveStage.mutate(e.target.value)}
                    disabled={moveStage.isPending || !stages?.length}
                    className="font-semibold text-[11px] rounded-md px-1.5 py-0.5 border outline-none disabled:opacity-60"
                    style={{ borderColor: "var(--haip-border)", background: "var(--card)", color: "var(--primary)" }}
                  >
                    {!stages?.some(s => s.key === leadOwnerStage?.stage_key) && (
                      <option value="" disabled>
                        {leadOwnerStage?.stage_key ?? "Not set"}
                      </option>
                    )}
                    {(stages ?? []).map(s => (
                      <option key={s.id} value={s.id}>{s.label}</option>
                    ))}
                  </select>
                </div>
              </div>
            )}

            {/* HAIP Inbox full-parity pass, ticket 3: AI Conversation Summary
                -- reuses Inquiry.ai_summary/ai_analysis, already generated
                by generate_ai_summary.py and already present on the
                lead-detail response above. Zero new backend work. */}
            {leadOwnerStage?.ai_summary && (
              <div
                className="haip-card p-3.5 space-y-2"
                style={{ background: "color-mix(in srgb, var(--primary) 5%, transparent)" }}
              >
                <p className="text-[10px] font-bold uppercase tracking-wider flex items-center gap-1.5" style={{ color: "var(--haip-fg-subtle)" }}>
                  <Sparkles size={12} style={{ color: "var(--primary)" }} />
                  AI Conversation Summary
                </p>
                {leadOwnerStage.needs_agent_followup && (
                  <div
                    className="flex items-start gap-1.5 rounded-lg px-2 py-1.5 text-[11px] leading-snug"
                    style={{ background: "color-mix(in srgb, var(--haip-amber) 15%, transparent)", color: "var(--haip-amber)" }}
                  >
                    <UserCheck size={12} className="flex-shrink-0 mt-0.5" />
                    <span>
                      <strong>AI replied automatically — needs your follow-up.</strong>
                      {leadOwnerStage.needs_agent_followup_reason ? ` ${leadOwnerStage.needs_agent_followup_reason}` : ""}
                    </span>
                  </div>
                )}
                <p className="text-xs leading-relaxed" style={{ color: "var(--haip-fg)" }}>
                  {leadOwnerStage.ai_summary}
                </p>
                {leadOwnerStage.ai_analysis && (
                  <div className="pt-2 space-y-1 text-[11px]" style={{ borderTop: "1px solid var(--haip-border)" }}>
                    {leadOwnerStage.ai_analysis.intent && (
                      <div className="flex justify-between"><span style={{ color: "var(--haip-fg-subtle)" }}>Intent</span><span className="font-medium" style={{ color: "var(--haip-fg)" }}>{leadOwnerStage.ai_analysis.intent}</span></div>
                    )}
                    {leadOwnerStage.ai_analysis.sentiment && (
                      <div className="flex justify-between"><span style={{ color: "var(--haip-fg-subtle)" }}>Sentiment</span><span className="font-medium capitalize" style={{ color: "var(--haip-fg)" }}>{leadOwnerStage.ai_analysis.sentiment}</span></div>
                    )}
                    {leadOwnerStage.ai_analysis.objection && (
                      <div className="flex justify-between"><span style={{ color: "var(--haip-fg-subtle)" }}>Objection</span><span className="font-medium" style={{ color: "var(--haip-fg)" }}>{leadOwnerStage.ai_analysis.objection}</span></div>
                    )}
                    {leadOwnerStage.ai_analysis.next_action && (
                      <div className="flex justify-between"><span style={{ color: "var(--haip-fg-subtle)" }}>Next action</span><span className="font-medium" style={{ color: "var(--haip-fg)" }}>{leadOwnerStage.ai_analysis.next_action}</span></div>
                    )}
                  </div>
                )}
              </div>
            )}

            {/* Recent stays */}
            {(guest?.recent_stays ?? []).length > 0 && (
              <div>
                <p className="text-[10px] font-medium uppercase tracking-wider mb-2" style={{ color: "var(--haip-fg-subtle)" }}>
                  Recent stays
                </p>
                <div className="space-y-2">
                  {guest!.recent_stays!.slice(0, 3).map((s, i) => (
                    <div key={i} className="flex items-start gap-2">
                      <Bed size={10} className="mt-0.5 flex-shrink-0" style={{ color: "var(--primary)" }} />
                      <div className="min-w-0">
                        <p className="text-xs font-medium truncate" style={{ color: "var(--haip-fg)" }}>
                          {s.property_name || "Property"}
                        </p>
                        {s.check_in && (
                          <p className="text-[10px]" style={{ color: "var(--haip-fg-subtle)" }}>
                            {new Date(s.check_in).toLocaleDateString("en-IN", { day: "numeric", month: "short" })}
                            {s.check_out && ` → ${new Date(s.check_out).toLocaleDateString("en-IN", { day: "numeric", month: "short" })}`}
                          </p>
                        )}
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* Consent */}
            {guest?.consent_status && (
              <div className="flex items-center gap-1.5">
                <div
                  className="w-1.5 h-1.5 rounded-full flex-shrink-0"
                  style={{ background: guest.consent_status === "granted" ? "var(--haip-green)" : "var(--haip-amber)" }}
                />
                <span className="text-[10px] capitalize" style={{ color: "var(--haip-fg-subtle)" }}>
                  Consent {guest.consent_status}
                </span>
              </div>
            )}

            {/* HAIP Inbox prototype-wiring plan, ticket 5 */}
            <ProfileCompletenessWidget inquiryId={detail.inquiry_id ?? null} />
            <FollowUpTasksPanel conversationId={detail.id} />
          </>
        )}
      </div>

    </div>
  );
}
